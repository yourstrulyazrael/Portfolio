-- Portfolio schema for Supabase (Postgres).
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- It is safe to re-run: every statement is idempotent.

-- Case-insensitive text, so "javascript" and "JavaScript" count as the same
-- technology (matches the old MySQL collation).
create extension if not exists citext;

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username varchar(50) not null unique,
    password varchar(255) not null
);

create table if not exists public.skills (
    id bigint generated by default as identity primary key,
    name citext not null,
    category varchar(50) not null,
    proficiency varchar(50) not null
);

create table if not exists public.technologies (
    id bigint generated by default as identity primary key,
    name citext not null unique
);

create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    title varchar(100) not null,
    description text not null,
    github_url varchar(255)
);

create table if not exists public.project_technologies (
    project_id bigint not null references public.projects(id) on delete cascade,
    technology_id bigint not null references public.technologies(id) on delete cascade,
    primary key (project_id, technology_id)
);

-- The image with the lowest sort_order is the project's cover.
create table if not exists public.project_images (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.projects(id) on delete cascade,
    filename varchar(255) not null,
    sort_order int not null default 0,
    created_at timestamptz not null default now()
);

create index if not exists project_images_project_id_idx on public.project_images (project_id);

create table if not exists public.certificates (
    id bigint generated by default as identity primary key,
    title varchar(150) not null,
    issuer varchar(150) not null,
    issue_date date,
    credential_url varchar(255),
    description text,
    file varchar(255),
    created_at timestamptz not null default now()
);

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    email varchar(255) not null,
    message text not null,
    created_at timestamptz not null default now()
);

-- The Flask app connects with the secret (service role) key, which bypasses RLS.
-- Enabling RLS with no policies means the public anon key can read or write nothing.
alter table public.users enable row level security;
alter table public.skills enable row level security;
alter table public.technologies enable row level security;
alter table public.projects enable row level security;
alter table public.project_technologies enable row level security;
alter table public.project_images enable row level security;
alter table public.certificates enable row level security;
alter table public.messages enable row level security;

-- Public bucket for project images and certificate files.
-- Anyone can view files by URL; only the secret key can upload or delete.
insert into storage.buckets (id, name, public)
values ('portfolio', 'portfolio', true)
on conflict (id) do nothing;
