create extension if not exists citext;

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username varchar(50) not null unique,
    password varchar(255) not null
);

alter table public.users add column if not exists failed_logins int not null default 0;
alter table public.users add column if not exists locked_until timestamptz;

create table if not exists public.skills (
    id bigint generated by default as identity primary key,
    name citext not null,
    category varchar(50) not null,
    proficiency varchar(50) not null
);

create table if not exists public.technologies (
    id bigint generated by default as identity primary key,
    name citext not null unique
);

create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    title varchar(100) not null,
    description text not null,
    github_url varchar(255),
    live_url varchar(255),
    demo_credentials jsonb not null default '[]'::jsonb
);

alter table public.projects add column if not exists live_url varchar(255);
alter table public.projects add column if not exists demo_credentials jsonb not null default '[]'::jsonb;

create table if not exists public.project_technologies (
    project_id bigint not null references public.projects(id) on delete cascade,
    technology_id bigint not null references public.technologies(id) on delete cascade,
    primary key (project_id, technology_id)
);

create table if not exists public.project_images (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.projects(id) on delete cascade,
    filename varchar(255) not null,
    sort_order int not null default 0,
    created_at timestamptz not null default now()
);

create index if not exists project_images_project_id_idx on public.project_images (project_id);

create table if not exists public.certificates (
    id bigint generated by default as identity primary key,
    title varchar(150) not null,
    issuer varchar(150) not null,
    issue_date date,
    credential_url varchar(255),
    description text,
    file varchar(255),
    created_at timestamptz not null default now()
);

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    name varchar(100) not null,
    email varchar(255) not null,
    message text not null,
    created_at timestamptz not null default now()
);

alter table public.users enable row level security;
alter table public.skills enable row level security;
alter table public.technologies enable row level security;
alter table public.projects enable row level security;
alter table public.project_technologies enable row level security;
alter table public.project_images enable row level security;
alter table public.certificates enable row level security;
alter table public.messages enable row level security;

insert into storage.buckets (id, name, public)
values ('portfolio', 'portfolio', true)
on conflict (id) do nothing;

create table if not exists public.site_settings (
    id int primary key default 1 check (id = 1),
    theme varchar(10) not null default 'system' check (theme in ('system', 'light', 'dark')),
    accent varchar(20) not null default 'emerald',
    updated_at timestamptz not null default now()
);

alter table public.site_settings drop constraint if exists site_settings_accent_check;
alter table public.site_settings add constraint site_settings_accent_check
    check (accent in ('emerald', 'violet', 'blue', 'cyan', 'amber', 'rose', 'orange', 'pink', 'lime', 'indigo', 'mono'));

insert into public.site_settings (id) values (1) on conflict (id) do nothing;

alter table public.site_settings enable row level security;

